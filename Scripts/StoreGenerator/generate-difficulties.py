#!/usr/bin/env python3
"""Emit difficulty metadata alongside the bundled SQLite catalog, never runtime JSON."""
import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--seed', type=Path, default=ROOT / 'Scripts/StoreGenerator/SeedData.json')
parser.add_argument('--output', type=Path, default=ROOT / 'onlybody/Products/OnlyBody/Catalog/ExerciseDifficultyCatalog.swift')
parser.add_argument('--check', action='store_true')
args = parser.parse_args()
TARGET = args.output
rows = json.loads(args.seed.read_text())
assert len({row['name'] for row in rows}) == len(rows)
lines = [
    '// Generated by Scripts/StoreGenerator/generate-difficulties.py.',
    '/// Relative progression levels for the exact named exercise variants.',
    'nonisolated enum ExerciseDifficultyCatalog {',
    '    static let levels: [String: ExerciseDifficulty] = ['
]
for row in rows:
    assert row['difficulty'] in ('beginner', 'intermediate', 'advanced')
    lines.append(f"        {json.dumps(row['name'])}: .{row['difficulty']},")
lines += ['    ]', '}', '']
content = '\n'.join(lines)
if args.check:
    assert TARGET.read_text() == content, 'Regenerate difficulty catalog'
    print('Every seed exercise has an explicit difficulty; generated Swift is current.')
else:
    TARGET.write_text(content)
