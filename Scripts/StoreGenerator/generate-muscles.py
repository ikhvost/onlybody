#!/usr/bin/env python3
"""Generate release muscle profiles without changing persistent exercise identity."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
TARGET = ROOT / 'onlybody/onlybody/Domain/Catalog/ExerciseMuscleCatalog.swift'
rows = json.loads((ROOT / 'Scripts/StoreGenerator/SeedData.json').read_text())
assert len({row['name'] for row in rows}) == len(rows)
groups = {'Chest', 'Back', 'Shoulders', 'Biceps', 'Triceps', 'Forearms', 'Serratus',
          'Core', 'Quads', 'Glutes', 'Hamstrings', 'Calves', 'Hip Flexors', 'Adductors'}
lines = ['// Generated by Scripts/StoreGenerator/generate-muscles.py.',
         '/// Qualitative roles for the named variants, not measured activation percentages.',
         'nonisolated enum ExerciseMuscleCatalog {',
         '    static let profiles: [String: ExerciseMuscleProfile] = [']
for row in rows:
    primary, secondary = row['primaryMuscles'], row['secondaryMuscles']
    assert primary and set(primary + secondary) <= groups
    assert len(set(primary + secondary)) == len(primary + secondary)
    lines += [f'        {json.dumps(row["name"])}: ExerciseMuscleProfile(',
              f'            primary: {json.dumps(primary)},',
              f'            secondary: {json.dumps(secondary)},',
              f'            isFullBody: {str(row["isFullBody"]).lower()}),']
lines += ['    ]', '}', '']
content = '\n'.join(lines)
parser = argparse.ArgumentParser(description=__doc__)
parser.add_argument('--check', action='store_true')
if parser.parse_args().check:
    assert TARGET.read_text() == content, 'Regenerate muscle catalog'
    print(f'Validated muscle profiles for {len(rows)} exercises.')
else:
    TARGET.write_text(content)
