#!/usr/bin/env python3
"""Validate authoring data and emit an immutable Swift catalog; no runtime JSON."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
TARGET = ROOT / 'onlybody/Products/OnlyBody/Catalog/ExerciseDemonstrationCatalog.swift'


def render(catalog_path, seed_path, require_complete):
    rows = json.loads(catalog_path.read_text())
    seed = json.loads(seed_path.read_text())
    names = [row['exerciseName'] for row in rows]
    keys = [row['key'] for row in rows]
    assert len(names) == len(set(names)), 'Duplicate exercise'
    seed_names = {row['name'] for row in seed}
    assert set(names) <= seed_names, 'Unknown exercise'
    if require_complete:
        assert set(names) == seed_names, 'Missing exercise demonstration'
    assert len(keys) == len(set(keys)), 'Duplicate stable media key'
    output = [
        f'// Generated by Scripts/ExerciseMedia/generate.py. Edit {catalog_path.name}, then regenerate.',
        '/// Release-managed YouTube demonstrations, keyed independently of seed-store UUIDs.',
        'nonisolated enum ExerciseDemonstrationCatalog {',
        '    static let all: [ExerciseDemonstration] = ['
    ]
    for row in rows:
        assert re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', row['key'])
        assert re.fullmatch(r'[A-Za-z0-9_-]{11}', row['videoID'])
        assert isinstance(row['startSeconds'], int) and row['startSeconds'] >= 0
        assert row['author'].strip()
        assert row['reviewStatus'] in {'browser-embed-and-visual-sample', 'partial-review-user-deferred'}
        if row['reviewStatus'] == 'partial-review-user-deferred':
            assert (catalog_path.parent / row['reviewReference']).is_file(), 'Missing partial review record'
        assert re.fullmatch(r'\d{4}-\d{2}-\d{2}', row['reviewedOn'])
        quote = lambda key: json.dumps(row[key], ensure_ascii=False)
        output.extend([
            '        ExerciseDemonstration(',
            f'            id: {quote("key")}, exerciseName: {quote("exerciseName")},',
            f'            videoID: {quote("videoID")}, author: {quote("author")}, startSeconds: {row["startSeconds"]}',
            '        ),'
        ])
    if rows:
        output[-1] = '        )'
    output.extend([
        '    ]', '',
        '    /// Exact names deliberately make catalog renames an explicit content migration.',
        '    static func demonstration(for exerciseName: String) -> ExerciseDemonstration? {',
        '        all.first { $0.exerciseName == exerciseName }',
        '    }', '}', ''
    ])
    return '\n'.join(output)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    parser.add_argument('--catalog', type=Path, default=HERE / 'catalog.json')
    parser.add_argument('--seed', type=Path, default=ROOT / 'Scripts/StoreGenerator/SeedData.json')
    parser.add_argument('--output', type=Path, default=TARGET)
    parser.add_argument('--allow-missing', action='store_true')
    args = parser.parse_args()
    content = render(args.catalog, args.seed, not args.allow_missing)
    if args.check:
        assert args.output.read_text() == content, 'Run python3 Scripts/ExerciseMedia/generate.py'
        print('Exercise media catalog satisfies coverage policy; generated Swift is current.')
    else:
        args.output.write_text(content)
