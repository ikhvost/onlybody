#!/usr/bin/env python3
"""Validate authoring data and emit an immutable Swift catalog; no runtime JSON."""
import argparse
import json
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parents[2]
HERE = Path(__file__).resolve().parent
TARGET = ROOT / 'onlybody/onlybody/Domain/Catalog/ExerciseDemonstrationCatalog.swift'


def render():
    rows = json.loads((HERE / 'catalog.json').read_text())
    seed = json.loads((ROOT / 'Scripts/StoreGenerator/SeedData.json').read_text())
    names = [row['exerciseName'] for row in rows]
    keys = [row['key'] for row in rows]
    assert len(names) == len(set(names)) == len(seed), 'Missing or duplicate exercise'
    assert set(names) == {row['name'] for row in seed}, 'Seed catalog mismatch'
    assert len(keys) == len(set(keys)), 'Duplicate stable media key'
    output = [
        '// Generated by Scripts/ExerciseMedia/generate.py. Edit catalog.json, then regenerate.',
        '/// Release-managed YouTube demonstrations, keyed independently of seed-store UUIDs.',
        'nonisolated enum ExerciseDemonstrationCatalog {',
        '    static let all: [ExerciseDemonstration] = ['
    ]
    for row in rows:
        assert re.fullmatch(r'[a-z0-9]+(?:-[a-z0-9]+)*', row['key'])
        assert re.fullmatch(r'[A-Za-z0-9_-]{11}', row['videoID'])
        assert isinstance(row['startSeconds'], int) and row['startSeconds'] >= 0
        assert row['author'].strip()
        assert row['reviewStatus'] == 'browser-embed-and-visual-sample'
        assert re.fullmatch(r'\d{4}-\d{2}-\d{2}', row['reviewedOn'])
        quote = lambda key: json.dumps(row[key], ensure_ascii=False)
        output.extend([
            '        ExerciseDemonstration(',
            f'            id: {quote("key")}, exerciseName: {quote("exerciseName")},',
            f'            videoID: {quote("videoID")}, author: {quote("author")}, startSeconds: {row["startSeconds"]}',
            '        ),'
        ])
    output[-1] = '        )'
    output.extend([
        '    ]', '',
        '    /// Exact names deliberately make catalog renames an explicit content migration.',
        '    static func demonstration(for exerciseName: String) -> ExerciseDemonstration? {',
        '        all.first { $0.exerciseName == exerciseName }',
        '    }', '}', ''
    ])
    return '\n'.join(output)


if __name__ == '__main__':
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    content = render()
    if args.check:
        assert TARGET.read_text() == content, 'Run python3 Scripts/ExerciseMedia/generate.py'
        print('Exercise media catalog covers every seed exercise; generated Swift is current.')
    else:
        TARGET.write_text(content)
